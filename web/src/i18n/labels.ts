export type EnumLabelKey = keyof typeof enumLabels;

export function metricLabel(key: MetricLabelKey | string): Bilingual {
  if (key in metricLabels) return metricLabels[key as MetricLabelKey];
  return { zh: key, en: '' };
}

export function enumLabel(value?: string | null): Bilingual {
  if (!value) return { zh: '等待数据', en: '' };
  const normalized = value.replace(/\s+/g, '_').toUpperCase();
  if (normalized in enumLabels) return enumLabels[normalized as EnumLabelKey];
  return { zh: value.replaceAll('_', ' '), en: normalized };
}

